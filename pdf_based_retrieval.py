from fastapi import UploadFile, File
from pypdf import PdfReader
from typing import List
import io
import numpy as np
import faiss

@app.post("/upload")
async def upload_pdfs(files: List[UploadFile] = File(...)):
    global chunks, embeddings, index

    all_chunks = []
    file_names = []

    for file in files:
        if not file.filename.lower().endswith(".pdf"):
            continue

        content = await file.read()
        reader = PdfReader(io.BytesIO(content))

        pdf_text = "\n".join(
            page.extract_text() or ""
            for page in reader.pages
        )

        pdf_chunks = split_text(pdf_text)

        all_chunks.extend(pdf_chunks)
        file_names.append(file.filename)

    if not all_chunks:
        raise HTTPException(
            status_code=400,
            detail="No readable text found in uploaded PDFs."
        )

    new_embeddings = embedding_model.encode(
        all_chunks,
        convert_to_numpy=True,
        show_progress_bar=False
    ).astype("float32")

    faiss.normalize_L2(new_embeddings)

    new_index = faiss.IndexFlatIP(new_embeddings.shape[1])
    new_index.add(new_embeddings)

    chunks = all_chunks
    embeddings = new_embeddings
    index = new_index

    return {
        "message": "PDFs uploaded and indexed successfully",
        "files": file_names,
        "total_chunks": len(chunks)
    }

